module decoder(val,a,b,c,d,e,f,g);
//  I/O DEF ========================================================================================    
    input [3:0] val;            // 4B input value
    output reg a,b,c,d,e,f,g;   // 7SEG Output
// I/0 DEF [END] ===================================================================================
// PROGRAM =========================================================================================
    always @(*) begin
        case (val)
            4'b0000:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1111_10;   //   dx00
            4'b0001:    {a,    b,  c,  d,  e,  f,  g}   = 7'b0_1100_00;   //   dx01
            4'b0010:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1011_01;   //   dx02
            4'b0011:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1110_01;   //   dx03
            4'b0100:    {a,    b,  c,  d,  e,  f,  g}   = 7'b0_1100_11;   //   dx04
            4'b0101:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_0110_11;   //   dx05
            4'b0110:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_0111_11;   //   dx06
            4'b0111:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1100_00;   //   dx07
            4'b1000:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1111_11;   //   dx08
            4'b1001:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1110_11;   //   dx09

            4'b1010:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_1101_11;   //   dx10
            4'b1011:    {a,    b,  c,  d,  e,  f,  g}   = 7'b0_0111_11;   //   dx11
            4'b1100:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_0011_10;   //   dx12
            4'b1101:    {a,    b,  c,  d,  e,  f,  g}   = 7'b0_1111_01;   //   dx13
            4'b1110:    {a,    b,  c,  d,  e,  f,  g}   = 7'b1_0011_11;   //   dx14
            default:    {a,    b,  c,  d,  e,  f,  g}   = 7'b0_0000_00;   //   OFF
        endcase
    end
// PROGRAM [END] ===================================================================================
endmodule